    //Dibujar 
    private void drawLines(Graphics2D g2d, List<Point> linea, Color color) {
        g2d.setColor(color);
        for (int i = 0; i < linea.size() - 1; i++) {
            Point punto1 = linea.get(i);
            Point punto2 = linea.get(i + 1);
            g2d.drawLine(punto1.x, punto1.y, punto2.x, punto2.y);
        }
    }
    
    public void pintar(){
        this.repaint();
    }
    
    public void guardarDibujo() {
        BufferedImage imagen = new BufferedImage(getWidth(), getHeight(), BufferedImage.TYPE_INT_RGB);
        Graphics2D g2d = imagen.createGraphics();
        paint(g2d);

        JFileChooser fileChooser = new JFileChooser();
        int seleccion = fileChooser.showSaveDialog(this);

        if (seleccion == JFileChooser.APPROVE_OPTION) {
            File archivo = fileChooser.getSelectedFile();

            // Si el usuario no escribió .png al final, se lo agregamos automáticamente
            if (!archivo.getName().toLowerCase().endsWith(".png")) {
                archivo = new File(archivo.getAbsolutePath() + ".png");
            }

            try {
                ImageIO.write(imagen, "png", archivo);
                JOptionPane.showMessageDialog(null, "Dibujo guardado en: " + archivo.getAbsolutePath());
            } catch (IOException e) {
                e.printStackTrace();
            }
        }
    }
    
    @Override
    protected void paintComponent(Graphics g) {
        puntos.addAll(ServerHilo.puntos);
        grosor.addAll(ServerHilo.grosor);
        colores.addAll(ServerHilo.colores);
        textoEscRec.addAll(ServerHilo.textoEscRec);
        xRec.addAll(ServerHilo.xRec);
        yRec.addAll(ServerHilo.yRec);
        int k;
        super.paintComponent(g);
        
        Graphics2D g2d = (Graphics2D) g;
        
        k = 0;
        for (List<Point> linea : new ArrayList<>(puntos)) {
            g2d.setStroke(new BasicStroke(grosor.get(k)));
            drawLines(g2d, linea, colores.get(k));
            k++;
        }

        //Dibujar texto
        for (int i = 0; i < textoEscRec.size(); i++) {
            g2d.setColor(Color.decode("#000000"));
            g2d.drawString(textoEscRec.get(i), xRec.get(i), yRec.get(i));
        }
    }

